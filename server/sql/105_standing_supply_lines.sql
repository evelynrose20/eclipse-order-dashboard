-- Standing supply lines: real stock, real vehicles, linked factory/warehouse/garrison.
USE eclipse_order;
CREATE TABLE IF NOT EXISTS world_logistics_supply_lines (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(140) NOT NULL,
 source_kind ENUM('facility','warehouse') NOT NULL,
 source_id BIGINT UNSIGNED NOT NULL,
 destination_kind ENUM('warehouse','installation') NOT NULL,
 destination_id BIGINT UNSIGNED NOT NULL,
 item_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 quantity DECIMAL(15,3) NOT NULL,
 keep_at_least DECIMAL(15,3) NOT NULL DEFAULT 0,
 destination_target DECIMAL(15,3) NULL,
 transport_template_id BIGINT UNSIGNED NOT NULL,
 vehicle_lot_id BIGINT UNSIGNED NOT NULL,
 interval_minutes INT UNSIGNED NOT NULL DEFAULT 1440,
 next_due_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_dispatched_at DATETIME NULL,
 status ENUM('active','paused','waiting','retired') NOT NULL DEFAULT 'paused',
 wait_reason VARCHAR(180) NOT NULL DEFAULT '',
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(item_id) REFERENCES world_industry_items(id),
 FOREIGN KEY(transport_template_id) REFERENCES world_logistics_transport_templates(id),
 FOREIGN KEY(vehicle_lot_id) REFERENCES world_magitek_equipment_inventory(id),
 FOREIGN KEY(created_by) REFERENCES accounts(id),
 INDEX ix_supply_lines_due(status,next_due_at),
 CONSTRAINT chk_supply_line_quantity CHECK(quantity>0),
 CONSTRAINT chk_supply_line_interval CHECK(interval_minutes BETWEEN 15 AND 525600),
 CONSTRAINT chk_supply_line_reserve CHECK(keep_at_least>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS world_logistics_supply_line_shipments (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 supply_line_id BIGINT UNSIGNED NOT NULL,
 source_kind ENUM('facility','warehouse') NOT NULL,
 source_id BIGINT UNSIGNED NOT NULL,
 destination_kind ENUM('warehouse','installation') NOT NULL,
 destination_id BIGINT UNSIGNED NOT NULL,
 item_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 quantity DECIMAL(15,3) NOT NULL,
 transport_template_id BIGINT UNSIGNED NOT NULL,
 vehicle_lot_id BIGINT UNSIGNED NOT NULL,
 fuel_item_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 fuel_used DECIMAL(15,3) NOT NULL DEFAULT 0,
 route_segments JSON NOT NULL,
 status ENUM('in_transit','arrived','disrupted') NOT NULL DEFAULT 'in_transit',
 departure_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 due_at DATETIME NOT NULL,
 arrived_at DATETIME NULL,
 incident_notes VARCHAR(300) NOT NULL DEFAULT '',
 FOREIGN KEY(supply_line_id) REFERENCES world_logistics_supply_lines(id),
 FOREIGN KEY(item_id) REFERENCES world_industry_items(id),
 FOREIGN KEY(fuel_item_id) REFERENCES world_industry_items(id),
 FOREIGN KEY(transport_template_id) REFERENCES world_logistics_transport_templates(id),
 FOREIGN KEY(vehicle_lot_id) REFERENCES world_magitek_equipment_inventory(id),
 INDEX ix_supply_line_receipt(status,due_at),
 INDEX ix_supply_line_vehicle(vehicle_lot_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
